"""Rule-based daily briefing. Templates only: it reports observed moves, distances to the
owner's alert thresholds, triggered alerts and due journal reviews. It never infers a cause
for a price move and never suggests buying or selling."""

from __future__ import annotations

from datetime import UTC, date, datetime, timedelta
from decimal import Decimal
from zoneinfo import ZoneInfo

from sqlalchemy import select
from sqlalchemy.orm import Session

from marketdesk.models import Alert, AlertEvent, JournalEntry, Watchlist
from marketdesk.services.market import MarketDataService
from marketdesk.services.prefs import get_prefs
from marketdesk.services.watchlists import list_watchlists

METHOD = (
    "Generated by fixed rules from observed quotes, your alert thresholds, triggered alerts and journal "
    "review dates. No language model is used and no cause is inferred for any move."
)


def _fmt_price(v: Decimal, ccy: str | None) -> str:
    prefix = "₹" if ccy == "INR" else (f"{ccy} " if ccy else "")
    return f"{prefix}{v:,.2f}"


def _fmt_time(dt: datetime | None, tz: str) -> str:
    if dt is None:
        return "time unavailable"
    return dt.astimezone(ZoneInfo(tz)).strftime("%d %b %Y %H:%M %Z")


async def build_briefing(db: Session, market: MarketDataService, today: date) -> dict:
    prefs = get_prefs(db)
    tz = prefs["display_timezone"]
    items: list[dict] = []
    wl: Watchlist | None = None
    if prefs["default_watchlist_id"]:
        wl = db.get(Watchlist, prefs["default_watchlist_id"])
    if wl is None:
        lists = list_watchlists(db)
        wl = lists[0] if lists else None

    data_status = None
    if wl is not None and wl.items:
        symbols = [it.instrument.symbol for it in wl.items]
        results = await market.quotes(symbols)
        moves = []
        unusable = []
        statuses = set()
        for sym, r in results.items():
            statuses.add(r.meta.status)
            q = r.value
            if q is None or q.change_percent is None:
                unusable.append(sym)
                continue
            moves.append((q.change_percent, sym, q, r.meta.status))
        data_status = "stale" if "stale" in statuses else (next(iter(statuses)) if len(statuses) == 1 else None)
        moves.sort(key=lambda m: abs(m[0]), reverse=True)
        for pct, sym, q, status in moves[:3]:
            verb = "rose" if pct > 0 else ("fell" if pct < 0 else "was unchanged")
            tone = "positive" if pct > 0 else ("negative" if pct < 0 else "neutral")
            amount = f" {abs(pct):.2f}%" if pct != 0 else ""
            stale = " (stale data)" if status == "stale" else ""
            items.append(
                {
                    "kind": "move",
                    "tone": tone,
                    "symbol": sym,
                    "text": f"{sym} {verb}{amount} to {_fmt_price(q.last_price, q.instrument.currency)}{stale}.",
                    "detail": f"Versus previous close {_fmt_price(q.previous_close, q.instrument.currency)}; "
                    f"market time {_fmt_time(q.market_time, tz)}. Largest observed moves in {wl.name}.",
                }
            )
        if unusable:
            items.append(
                {
                    "kind": "coverage",
                    "tone": "warning",
                    "symbol": None,
                    "text": f"{len(unusable)} of {len(symbols)} symbols in {wl.name} have no usable change "
                    f"figure: {', '.join(unusable[:6])}.",
                    "detail": "Missing or unavailable quotes are excluded rather than treated as zero.",
                }
            )
    elif wl is not None:
        items.append(
            {
                "kind": "info",
                "tone": "info",
                "symbol": None,
                "text": f"{wl.name} is empty. Add symbols to see observed moves here.",
                "detail": None,
            }
        )
    else:
        items.append(
            {
                "kind": "info",
                "tone": "info",
                "symbol": None,
                "text": "No watchlist yet. Create one to see observed moves here.",
                "detail": None,
            }
        )

    # Distance to active alert thresholds (closest first).
    active = list(db.scalars(select(Alert).where(Alert.active.is_(True), Alert.rule.in_(("PRICE", "CROSS")))))
    if active:
        res = await market.quotes(list({a.instrument.symbol for a in active}))
        dist = []
        for a in active:
            r = res.get(a.instrument.symbol)
            if r is None or r.value is None:
                continue
            price = r.value.last_price
            gap = (a.target_price - price) / price * 100
            dist.append((abs(gap), gap, a, price, r.meta.status))
        dist.sort(key=lambda d: d[0])
        for _, gap, a, price, status in dist[:3]:
            side = "above" if gap > 0 else "below"
            stale = " (stale data)" if status == "stale" else ""
            items.append(
                {
                    "kind": "threshold",
                    "tone": "info",
                    "symbol": a.instrument.symbol,
                    "text": f"{a.instrument.symbol} is {abs(gap):.2f}% {'below' if side == 'above' else 'above'} your "
                    f"{a.direction.lower()} alert at {_fmt_price(a.target_price, a.instrument.currency)}{stale}.",
                    "detail": f"Last observed {_fmt_price(price, a.instrument.currency)}.",
                }
            )

    since = datetime.now(UTC) - timedelta(hours=24)
    events = list(
        db.execute(
            select(AlertEvent, Alert)
            .join(Alert, Alert.id == AlertEvent.alert_id)
            .where(AlertEvent.triggered_at >= since)
            .order_by(AlertEvent.triggered_at.desc())
            .limit(5)
        )
    )
    for ev, a in events:
        items.append(
            {
                "kind": "alert",
                "tone": "warning",
                "symbol": a.instrument.symbol,
                "text": f"Alert triggered: {a.instrument.symbol}.",
                "detail": (ev.explanation or "")
                + f" Detected {_fmt_time(ev.triggered_at, tz)}; market time {_fmt_time(ev.observed_market_time, tz)}.",
            }
        )

    due = list(
        db.scalars(
            select(JournalEntry)
            .where(JournalEntry.review_date.is_not(None), JournalEntry.review_date <= today)
            .order_by(JournalEntry.review_date)
            .limit(3)
        )
    )
    for e in due:
        items.append(
            {
                "kind": "review",
                "tone": "info",
                "symbol": e.instrument.symbol,
                "text": f"Journal review due for {e.instrument.symbol}: “{e.title}”.",
                "detail": f"Review date {e.review_date.isoformat()}.",
            }
        )

    return {
        "generated_at": datetime.now(UTC),
        "watchlist_id": wl.id if wl else None,
        "watchlist_name": wl.name if wl else None,
        "items": items,
        "method": METHOD,
        "data_status": data_status,
    }
